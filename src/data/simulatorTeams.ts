export function getTeamById(id: string): SimTeam {
  return SIMULATOR_TEAMS.find((t) => t.id === id) || SIMULATOR_TEAMS[0];
}

export const ALL_SIM_PLAYERS_POOL: { player: SimPlayer; teamName: string }[] = (() => {
  const seen = new Set<string>();
  const list: { player: SimPlayer; teamName: string }[] = [];
  for (const team of SIMULATOR_TEAMS) {
    for (const pl of [...team.starters, ...team.bench]) {
      const key = pl.name.toLowerCase();
      if (!seen.has(key)) {
        seen.add(key);
        list.push({ player: pl, teamName: team.shortName });
      }
    }
  }
  return list.sort((a, b) => b.player.overall - a.player.overall);
})();
