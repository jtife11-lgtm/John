function p(
  teamId: string,
  name: string,
  jersey: number,
  position: string,
  overall: number,
  overrideStats?: Partial<SimPlayer['stats']>
): SimPlayer {
  const parts = name.trim().split(' ');
  const shortName = parts.length > 1 ? parts[parts.length - 1] : name;
  const posUpper = position.toUpperCase();
  let roleGroup: RoleGroup = 'MID';
  if (posUpper === 'GK') roleGroup = 'GK';
  else if (['CB', 'LB', 'RB', 'LWB', 'RWB'].includes(posUpper)) roleGroup = 'DEF';
  else if (['ST', 'CF', 'LW', 'RW'].includes(posUpper)) roleGroup = 'FWD';

  const base = overall;
  const stats =
    roleGroup === 'GK'
      ? {
          pac: base - 2,
          sho: base - 4,
          pas: base - 5,
          dri: base - 1,
          def: base,
          phy: base - 2,
          ...overrideStats,
        }
      : roleGroup === 'DEF'
      ? {
          pac: base - 6,
          sho: base - 22,
          pas: base - 8,
          dri: base - 10,
          def: base + 1,
          phy: base,
          ...overrideStats,
        }
      : roleGroup === 'MID'
      ? {
          pac: base - 7,
          sho: base - 9,
          pas: base + 2,
          dri: base,
          def: posUpper === 'CDM' ? base - 2 : base - 14,
          phy: base - 6,
          ...overrideStats,
        }
      : {
          pac: base + 1,
          sho: base + 2,
          pas: base - 8,
          dri: base,
          def: base - 38,
          phy: base - 8,
          ...overrideStats,
        };

  return {
    id: `${teamId}-${jersey}-${shortName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
    name,
    shortName,
    jersey,
    position: posUpper,
    roleGroup,
    overall,
    stats: {
      pac: Math.max(40, Math.min(99, stats.pac)),
      sho: Math.max(35, Math.min(99, stats.sho)),
      pas: Math.max(45, Math.min(99, stats.pas)),
      dri: Math.max(45, Math.min(99, stats.dri)),
      def: Math.max(30, Math.min(99, stats.def)),
      phy: Math.max(45, Math.min(99, stats.phy)),
    },
    tsdbSearchName: name,
  };
}

function buildTeam(
  config: Omit<SimTeam, 'ratings'> & { att?: number; mid?: number; def?: number; gk?: number }
): SimTeam {
  const f = config.starters.filter((s) => s.roleGroup === 'FWD');
  const m = config.starters.filter((s) => s.roleGroup === 'MID');
  const d = config.starters.filter((s) => s.roleGroup === 'DEF');
  const g = config.starters.find((s) => s.roleGroup === 'GK');

  const avg = (arr: SimPlayer[], fallback: number) =>
    arr.length ? Math.round(arr.reduce((sum, x) => sum + x.overall, 0) / arr.length) : fallback;

  const att = config.att ?? avg(f, 82);
  const mid = config.mid ?? avg(m, 82);
  const def = config.def ?? avg(d, 81);
  const gk = config.gk ?? (g ? g.overall : 82);
  const ovr = Math.round((att + mid + def + gk) / 4);

  return {
    id: config.id,
    name: config.name,
    shortName: config.shortName,
    abbr: config.abbr,
    league: config.league,
    competitionTag: config.competitionTag,
    isNational: config.isNational,
    primaryColor: config.primaryColor,
    secondaryColor: config.secondaryColor,
    logoUrl: config.logoUrl,
    defaultFormation: config.defaultFormation,
    tacticalStyle: config.tacticalStyle,
    ratings: { att, mid, def, gk, ovr },
    starters: config.starters,
    bench: config.bench,
  };
}

